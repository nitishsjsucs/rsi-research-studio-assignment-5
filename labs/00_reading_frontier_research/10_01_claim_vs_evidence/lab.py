def write_cards(path):
    lines = ["# Claim vs evidence: the three papers this repo rebuilds\n",
             "Generated by `lab.py`. Each claim is paired with the experiment that supports it and the conditions that limit it.\n"]
    for c in CARDS:
        lines.append(f"\n## {c['paper']}\n")
        lines.append("| # | Claim | Supporting evidence (as summarised) | What remains untested |")
        lines.append("|---|---|---|---|")
        for i, (cl, ev, un) in enumerate(c["claims"], 1):
            lines.append(f"| {i} | {cl} | {ev} | {un} |")
        lines.append(f"\n**Laptop adaptation preserves:** {c['preserves']}.\n")
        lines.append(f"**Laptop adaptation changes:** {c['changes']}.\n")
    with open(path, "w") as f:
        f.write("\n".join(lines))


def main():
    a = _lab.args(default_seeds=1, edits=16)
    n_edits = 8 if a.quick else a.edits
    _lab.banner("10.01", "Distinguish claim from evidence", "Does the best score after selection survive re-measurement?")
    clock = _lab.Clock()

    _lab.section("Part A: claim cards")
    out = os.path.join(HERE, "claim_evidence_analysis.md")
    write_cards(out)
    for c in CARDS:
        print(f"  {c['paper']}: {len(c['claims'])} claims")
    print(f"  wrote {os.path.relpath(out, _lab.ROOT)}")

    _lab.section(f"Part B: the winner's curse on {n_edits} candidate edits")
    parent = Genome(ngram=3, word_weight=2.0, init="frequency", iters=2000, restarts=4)
    rng = np.random.default_rng(7)
    with Evaluator() as ev:
        steer = Scorer(ev, "steering", (0,), caller="10.01-select")
        fresh = Scorer(ev, "steering", (1, 2), caller="10.01-fresh-seeds")
        unseen = Scorer(ev, "probe", (0, 1), caller="10.01-unseen-ciphers")
        p0 = steer(parent)
        print(f"  parent: {parent.short()}  steering(seed 0) = {p0.rate:.3f}")
        ops = [op for op in applicable(parent) if UNIFORM_PRIOR[op.name]]
        picks = rng.choice(len(ops), size=min(n_edits, len(ops)), replace=False)
        rows = []
        for j in picks:
            op = ops[j]
            s = steer(op.apply(parent))
            rows.append((op.name, s.rate, s.rate - p0.rate))
        rows.sort(key=lambda r: -r[1])
        _lab.table(rows, ["edit", "steering", "gain"], {"steering": "{:.3f}", "gain": "{:+.3f}"})
        winner_name = rows[0][0]
        winner = next(op for op in ops if op.name == winner_name).apply(parent)
        headline = rows[0][2]
        f_par, f_win = fresh(parent), fresh(winner)
        u_par, u_win = unseen(parent), unseen(winner)
        beat_by_luck = sum(1 for r in rows if r[2] > 0)

        _lab.section("Headline vs evidence")
        _lab.table([
            ("steering, seed 0 (used to SELECT)", p0.rate, steer(winner).rate, headline),
            ("steering, fresh seeds 1-2", f_par.rate, f_win.rate, f_win.rate - f_par.rate),
            ("unseen probe ciphers, seeds 0-1", u_par.rate, u_win.rate, u_win.rate - u_par.rate),
        ], ["measurement", "parent", f"winner ({winner_name})", "gain"],
            {"parent": "{:.3f}", f"winner ({winner_name})": "{:.3f}", "gain": "{:+.3f}"})
        shrink = headline - (f_win.rate - f_par.rate)
        print(f"\n  {beat_by_luck}/{len(rows)} edits 'beat' the parent on the selection split.")
        print(f"  The headline gain {headline:+.3f} shrinks by {shrink:+.3f} on fresh seeds of the SAME ciphers.")
        print("  Claim: 'edit X improves the solver by the headline amount'.")
        print("  Evidence: only the re-measured gains, with their spread, support a claim.")
        save_json("10_01_winners_curse.json", {"parent": parent, "rows": rows, "winner": winner_name,
                                               "headline": headline, "fresh_gain": f_win.rate - f_par.rate,
                                               "unseen_gain": u_win.rate - u_par.rate})
    print(f"\ndone in {clock}")


if __name__ == "__main__":
    main()
